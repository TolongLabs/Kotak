import { randomBytes, randomUUID } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, relative, resolve, sep } from 'node:path'
import { parseArgs } from 'node:util'
import { jobstreetDatabase } from '../apps/api/src/scrapers/jobstreet/database'

const { values } = parseArgs({
  args: Bun.argv.slice(2),
  options: {
    username: { type: 'string' },
    'password-env': { type: 'string' },
    output: { type: 'string', default: '.local/admin-credentials.txt' },
    'reset-password': { type: 'boolean', default: false },
    help: { type: 'boolean', default: false }
  },
  strict: true
})

if (values.help) {
  console.info('Create a provisioned scraper admin: bun run admin:create --username admin')
  console.info('Options: --password-env ENV_NAME, --output .local/admin-credentials.txt, --reset-password')
  console.info('Passwords are generated by default and written to the ignored .local directory, never printed.')
  process.exit(0)
}

const username = values.username?.trim().toLowerCase()
if (!username || !/^[a-z0-9][a-z0-9._-]{2,63}$/.test(username))
  throw new Error('Use --username with 3–64 lowercase letters, numbers, dots, underscores or hyphens.')
const databaseUrl = Bun.env.DATABASE_URL?.trim()
if (!databaseUrl) throw new Error('Set DATABASE_URL to the production Neon connection URL.')
const password = values['password-env'] ? Bun.env[values['password-env']] : randomBytes(30).toString('base64url')
if (!password || new TextEncoder().encode(password).length < 16 || new TextEncoder().encode(password).length > 72)
  throw new Error('The password must contain 16–72 UTF-8 bytes.')

// Keep generated credentials in the repository's ignored local directory.
const output = resolve(values.output!)
const localRoot = resolve('.local')
const relativeOutput = relative(localRoot, output)
if (!relativeOutput || relativeOutput === '..' || relativeOutput.startsWith(`..${sep}`) || isAbsolute(relativeOutput))
  throw new Error('--output must be a file inside the ignored .local directory.')
await mkdir(dirname(output), { recursive: true })
// Reserve the credential file before changing the database; never overwrite a saved password silently.
await writeFile(
  output,
  `Kotak Scraper Admin\n\nSign in: https://kotak.tp073654.workers.dev/admin/sign-in\nUsername: ${username}\nPassword: ${password}\n\nKeep this file private. It is Git-ignored.\n`,
  { flag: 'wx', mode: 0o600 }
)

const sql = jobstreetDatabase(databaseUrl)
try {
  if (values['reset-password']) {
    const results = await sql.transaction([
      sql.query(
        `UPDATE scraper_admin_users
         SET password_hash = crypt($2::text, gen_salt('bf', 12)),
             failed_login_attempts = 0, locked_until = NULL
         WHERE username = $1 AND enabled = true RETURNING id`,
        [username, password]
      ),
      sql.query(
        `DELETE FROM scraper_admin_sessions WHERE user_id IN
         (SELECT id FROM scraper_admin_users WHERE username = $1)`,
        [username]
      )
    ])
    if (!results[0].length) throw new Error('No enabled admin with that username exists.')
  } else {
    await sql.query(
      `INSERT INTO scraper_admin_users (id, username, password_hash)
       VALUES ($1, $2, crypt($3::text, gen_salt('bf', 12)))`,
      [randomUUID(), username, password]
    )
  }
  console.info(`Admin ${values['reset-password'] ? 'password reset' : 'created'}: ${username}`)
  console.info(`Credentials saved privately to ${output}; password was not printed.`)
} catch (error) {
  // The file stays reserved on error so an existing password can never be replaced accidentally.
  const code = error && typeof error === 'object' && 'code' in error ? String(error.code) : undefined
  console.error(
    code === '23505'
      ? 'That admin already exists. Use --reset-password explicitly to rotate its password.'
      : 'Admin provisioning failed. Check database migrations and credentials; no password was printed.'
  )
  process.exitCode = 1
}
